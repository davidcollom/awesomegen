const (
	TOCHeader = "Table of Contents"
)

// ErrNoEntries is returned when a list renders without a single entry.
//
// A README without entries is never useful, and writing one over an existing
// file empties a curated list, so the renderer refuses to produce one.
var ErrNoEntries = errors.New("no entries to render")

// section is a heading of the generated document together with the entries
// that belong to it.
type section struct {
	level int
	plain string
	items []*config.Item
	subs  []*section

	// hideTitle suppresses the heading itself, which is used for the
	// fallback group of a nested topic grouping when it is the only one.
	hideTitle bool

	// title and anchor are resolved once the whole document has been
	// planned, so the table of contents and the headings always agree.
	title  string
	anchor string
}

// Markdown renders a list into Awesome-style Markdown.
//
// It returns an error rather than silently producing an empty document, so
// callers cannot overwrite an existing README with nothing.
func Markdown(list config.List) (string, error) {
	var buf strings.Builder
	doc := md.NewMarkdown(&buf)

	// GitHub assigns an anchor to every heading and numbers the duplicates
	// across the whole document, so the anchors are allocated in the order
	// the headings appear.
	anchors := newAnchorSet()

	// Header
	doc.H1(sanitizeText(list.Title)).LF()
	anchors.unique(plainText(list.Title))
	if len(list.Badges) > 0 {
		for _, u := range list.Badges {
			if safe := sanitizeURL(u); safe != "" {
				doc.PlainTextf("![badge](%s)", safe)
			}
		}
		doc.LF()
	}
	if list.Tagline != "" {
		doc.Blockquote(sanitizeText(list.Tagline)).LF()
	}

	// The table of contents is a heading itself and comes before the
	// sections it links to.
	anchors.unique(TOCHeader)

	sections := buildSections(list)
	resolveSections(sections, anchors)

	emitted := 0
	if len(sections) > 0 {
		doc.H2(TOCHeader).LF()
		for _, s := range sections {
			doc.PlainTextf("- [%s](#%s)", s.title, s.anchor)
		}
		doc.LF()
		emitted = writeSections(doc, sections, list)
	}
	if emitted == 0 {
		return "", fmt.Errorf("%w: list %q", ErrNoEntries, list.Title)
	}

	doc.HorizontalRule()
	doc.PlainText("*Generated by [awesomegen](https://github.com/davidcollom/awesomegen).*")

	if err := doc.Build(); err != nil {
		return "", fmt.Errorf("render markdown: %w", err)
	}

	// The Markdown library writes the line feed of the platform it runs on,
	// so the document would end up with carriage returns on Windows. The
	// line endings are normalised, so that the same list produces the same
	// README everywhere and the file does not change when it is regenerated
	// on another platform.
	return strings.ReplaceAll(buf.String(), "\r\n", "\n"), nil
}

// buildSections turns the list into the tree of sections that is rendered.
func buildSections(list config.List) []*section {
	if list.GroupByTopic {
		return topicSections(list, collectItems(list))
	}
	return categorySections(list)
}

// categorySections renders one section per configured category.
//
// This is the mode used when group_by_topic is false: the entries are listed
// in the order they were curated in, without being grouped by topic.
//
// A repository that appears in more than one category is only rendered in the
// first one: printing it twice looked like a bug.
func categorySections(list config.List) []*section {
	seen := map[string]struct{}{}
	var out []*section
	for _, c := range list.Categories {
		if c == nil {
			continue
		}
		name := c.Name
		if name == "" {
			name = "Repositories"
		}
		items := make([]*config.Item, 0, len(c.Items))
		for _, it := range c.Items {
			if it == nil {
				continue
			}
			if k := itemKey(it); k != "" {
				if _, dup := seen[k]; dup {
					continue
				}
				seen[k] = struct{}{}
			}
			items = append(items, it)
		}
		if len(items) == 0 {
			continue
		}
		out = append(out, &section{
			level: 3,
			plain: TitlecaseKeys(name, list.Locale),
			items: items,
		})
	}
	return out
}

// topicSections groups the entries by GitHub topic.
//
// A link has no topics, so it cannot be ranked and cannot be assigned to a
// topic. The links are kept in the fallback group, which is the group of
// the entries that do not match any of the ranked topics, so that they are
// rendered in every mode instead of being dropped.
func topicSections(list config.List, items []*config.Item) []*section {
	var links []*config.Item
	var repos []*config.Item
	for _, it := range items {
		if it == nil {
			continue
		}
		// The entries are classified the way they are rendered: an entry
		// that is a link is rendered as a link, everything else is a
		// repository.
		if it.IsLink() {
			links = append(links, it)
			continue
		}
		repos = append(repos, it)
	}

	ranked := rankTopTags(repos, list.TagAliases, list.MinTagCountValue(), list.TopTagsLimitValue())
	fallback := list.TopicFallbackValue()

	if list.TopicGroupingMode != nil && *list.TopicGroupingMode == config.TopicGroupingModeNested {
		nested := map[string]map[string][]*config.Item{}
		for _, it := range repos {
			p, s := primarySecondaryForRepo(it.GHMeta, ranked, list.TagAliases, fallback)
			if _, ok := nested[p]; !ok {
				nested[p] = map[string][]*config.Item{}
			}
			nested[p][s] = append(nested[p][s], it)
		}
		if len(links) > 0 {
			if _, ok := nested[fallback]; !ok {
				nested[fallback] = map[string][]*config.Item{}
			}
			nested[fallback][fallback] = append(nested[fallback][fallback], links...)
		}

		var out []*section
		for _, pk := range mapsSortedKeys(nested) {
			sec := nested[pk]
			primary := &section{level: 3, plain: TitlecaseKeys(pk, list.Locale)}
			for _, sk := range mapsSortedKeys(sec) {
				primary.subs = append(primary.subs, &section{
					level: 4,
					plain: TitlecaseKeys(sk, list.Locale),
					items: sec[sk],
					// The fallback group does not get a heading of its
					// own when it is the only group of the section.
					hideTitle: sk == fallback && len(sec) == 1,
				})
			}
			out = append(out, primary)
		}
		return out
	}

	// flat mode
	groups := map[string][]*config.Item{}
	for _, it := range repos {
		p, _ := primarySecondaryForRepo(it.GHMeta, ranked, list.TagAliases, fallback)
		groups[p] = append(groups[p], it)
	}
	if len(links) > 0 {
		groups[fallback] = append(groups[fallback], links...)
	}

	var out []*section
	for _, k := range mapsSortedKeys(groups) {
		out = append(out, &section{level: 3, plain: TitlecaseKeys(k, list.Locale), items: groups[k]})
	}
	return out
}

// collectItems returns the items of every category in configuration order.
//
// A repository that appears in more than one category is only returned once:
// rendering it twice looked like a bug and it skewed the topic ranking,
// which counts the topics of every item it sees.
func collectItems(list config.List) []*config.Item {
	var out []*config.Item
	seen := map[string]struct{}{}
	for _, c := range list.Categories {
		if c == nil {
			continue
		}
		for _, it := range c.Items {
			if it == nil {
				continue
			}
			if k := itemKey(it); k != "" {
				if _, ok := seen[k]; ok {
					continue
				}
				seen[k] = struct{}{}
			}
			out = append(out, it)
		}
	}
	return out
}

// itemKey returns a stable identity for an item, used to de-duplicate.
//
// The identity follows the type of the item: an entry that is a link stays
// a link even when it names a repository, so it cannot take the identity of
// that repository away from the entry that is the repository itself.
func itemKey(it *config.Item) string {
	if it == nil {
		return ""
	}
	switch {
	case it.IsGitHub():
		if it.GHMeta != nil && it.GHMeta.FullName != "" {
			return "repo:" + it.GHMeta.FullName
		}
		if it.Repo != "" {
			return "repo:" + it.Repo
		}
	case it.IsLink():
		if it.URL != "" {
			return "link:" + it.URL
		}
	}
	return ""
}

// resolveSections allocates the anchor of every heading in the order the
// headings appear in the document and records the text that is rendered.
//
// The displayed text is sanitized, but the anchor is derived from the plain
// text: GitHub derives it from the text a reader sees, not from the
// Markdown source.
//
// A heading that is not rendered does not reserve an anchor either: GitHub
// only numbers the headings it renders, so a hidden heading must not push
// the headings after it to a numbered anchor that does not exist.
func resolveSections(sections []*section, anchors *anchorSet) {
	for _, s := range sections {
		s.plain = plainText(s.plain)
		s.title = markdownEscaper.Replace(s.plain)
		if !s.hideTitle {
			s.anchor = anchors.unique(s.plain)
		}
		resolveSections(s.subs, anchors)
	}
}

// writeSections renders the sections and returns the number of entries that
// were actually written.
func writeSections(doc *md.Markdown, sections []*section, list config.List) int {
	emitted := 0
	for _, s := range sections {
		if !s.hideTitle {
			doc.H3(s.title).LF()
		}
		emitted += writeItems(doc, s.items, list)
		doc.LF()
		for _, sub := range s.subs {
			if !sub.hideTitle {
				doc.H4(sub.title).LF()
			}
			emitted += writeItems(doc, sub.items, list)
			doc.LF()
		}
	}
	return emitted
}

// writeItems renders one list item per entry and returns the number of
// entries that were written.
//
// The order of the entries is preserved: it is the order they were curated
// in, either by the star list or by the configuration file.
func writeItems(doc *md.Markdown, items []*config.Item, list config.List) int {
	starsFormat := config.StarsFormatLocale
	if list.StarsFormat != nil {
		starsFormat = *list.StarsFormat
	}

	emitted := 0
	for _, it := range items {
		if it == nil {
			continue
		}
		// The declared type of the entry decides how it is rendered. An
		// entry that was declared as a link stays a link, even when it also
		// carries the metadata of a repository: the curated URL and title
		// are the ones that were configured.
		if it.IsLink() {
			if writeLinkItem(doc, it) {
				emitted++
			}
			continue
		}
		if m := it.GHMeta; m != nil {
			if writeRepoItem(doc, m, it, starsFormat, list.Locale) {
				emitted++
			}
		}
	}
	return emitted
}

// writeRepoItem renders a GitHub repository entry. It reports whether the
// entry was written: an entry without a usable URL is skipped.
func writeRepoItem(doc *md.Markdown, m *github.RepoMeta, it *config.Item, starsFormat config.StarsFormat, locale string) bool {
	url := sanitizeURL(m.URL)
	if url == "" {
		return false
	}

	// Every part carries the separator that belongs to it, so that an entry
	// without a description does not end with a dangling separator.
	tail := ""
	if stars := humanStars(m.Stars, starsFormat, locale); stars != "" {
		tail += " — ⭐ " + stars
	}
	if m.License != "" {
		tail += " · " + sanitizeText(m.License)
	}
	if desc := sanitizeText(m.Description); desc != "" {
		tail += " — " + desc
	}
	if it.Notes != "" {
		tail += " — " + sanitizeText(it.Notes)
	}
	doc.PlainTextf("- [%s](%s)%s",
		sanitizeText(m.FullName), url, tail)
	return true
}

// writeLinkItem renders an external link entry. It reports whether the entry
// was written: an entry without a usable URL is skipped.
func writeLinkItem(doc *md.Markdown, it *config.Item) bool {
	url := sanitizeURL(it.URL)
	if url == "" {
		return false
	}
	title := sanitizeText(it.Title)
	if title == "" {
		title = sanitizeText(it.URL)
	}
	note := ""
	if it.Notes != "" {
		note = " — " + sanitizeText(it.Notes)
	}
	doc.PlainTextf("- [%s](%s)%s", title, url, note)
	return true
}

func mapsSortedKeys[T any](m map[string]T) []string {
	keys := slices.Collect(maps.Keys(m))
	slices.Sort(keys)
	return keys
}

func primarySecondaryForRepo(m *github.RepoMeta, ranked []string, aliases map[string]string, fallback string) (string, string) {
	if m == nil {
		return fallback, fallback
	}
	// Build the set of this repo's canonical tags
	rtags := make([]string, 0, len(m.Topics))
	seen := map[string]struct{}{}
	for _, raw := range m.Topics {
		t := canonicalTag(raw, aliases)
		if t == "" {
			continue
		}
		if _, ok := seen[t]; ok {
			continue
		}
		seen[t] = struct{}{}
		rtags = append(rtags, t)
	}
	// primary = first tag that appears in ranked order
	primary := fallback
	for _, t := range ranked {
		for _, rt := range rtags {
			if rt == t {
				primary = t
				goto foundPrimary
			}
		}
	}
foundPrimary:
	// secondary = next ranked tag (distinct), else fallback
	secondary := fallback
	if primary != fallback {
		for _, t := range ranked {
			if t == primary {
				continue
			}
			for _, rt := range rtags {
				if rt == t {
					secondary = t
					goto foundSecondary
				}
			}
		}
	}
foundSecondary:
	return primary, secondary
}
